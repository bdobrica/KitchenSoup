"""Lock added/replaced transformation packages relative to the pinned CUDA base."""

import json
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[1]
image = (root / "images/model-transform/Dockerfile").read_text().splitlines()[0].split()[1]
script = """
import importlib.metadata as m
import json, subprocess
subprocess.run(['python3','-m','pip','uninstall','-y','vllm'], check=True)
before = {d.metadata['Name'].lower().replace('_','-'): d.version for d in m.distributions()}
subprocess.run(['python3','-m','pip','install','--no-cache-dir',
                '-r','/requirements.in'], check=True)
subprocess.run(['python3','/check_dependencies.py'], check=True)
after = {d.metadata['Name'].lower().replace('_','-'): d.version for d in m.distributions()}
print('LOCK_JSON=' + json.dumps({k:v for k,v in after.items() if before.get(k) != v}))
"""
result = subprocess.check_output(
    [
        "docker",
        "run",
        "--rm",
        "--platform",
        "linux/amd64",
        "--user",
        "0:0",
        "--volume",
        str(root / "images/model-transform/requirements.in") + ":/requirements.in:ro",
        "--volume",
        str(root / "scripts/check_transform_dependencies.py") + ":/check_dependencies.py:ro",
        "--entrypoint",
        "python3",
        image,
        "-c",
        script,
    ],
    text=True,
)
packages = json.loads(
    next(line[10:] for line in result.splitlines() if line.startswith("LOCK_JSON="))
)
(root / "images/model-transform/requirements.txt").write_text(
    "# Generated by scripts/lock_transform.py; edit requirements.in.\n"
    + "".join(f"{name}=={version}\n" for name, version in sorted(packages.items()))
)
